#!/usr/bin/env python3
"""Copy public raw evidence and generate the site's JavaScript data module."""
import json
import shutil
from pathlib import Path

root = Path(__file__).resolve().parents[1]
results = root / "bench" / "results"
site = root / "site"
evidence = {
    "startup": json.loads((results / "windows-amd64-startup.json").read_text(encoding="utf-8")),
    "replay": json.loads((results / "windows-amd64-replay.json").read_text(encoding="utf-8")),
    "proof": json.loads((results / "windows-amd64-proof.json").read_text(encoding="utf-8")),
}
output = "// Generated by bench/render_site.py from bench/results; do not edit.\n"
output += "export const evidence = " + json.dumps(evidence, ensure_ascii=False, separators=(",", ":")) + ";\n"
(site / "src").mkdir(parents=True, exist_ok=True)
(site / "src" / "results.js").write_text(output, encoding="utf-8", newline="\n")
public = site / "public" / "results"
public.mkdir(parents=True, exist_ok=True)
for name in ["windows-amd64-startup.json", "windows-amd64-replay.json", "windows-amd64-proof.json"]:
    shutil.copyfile(results / name, public / name)
print("site evidence updated")
